"""Live AI Monitoring endpoints.

/status     -> per-driver signal snapshot (simulation-generated by default;
               see README AI section for AI_MODE=live).
/events     -> real reads from the safety_events table. Also triggers a
               fresh detection pass for a couple of online drivers on each
               call (rate-limited), routed through app.services.safety_engine
               so incident/alert escalation is identical whether triggered
               by REST polling or by the WebSocket background loop in
               main.py.
/ai-status  -> what's actually active right now (demo vs live, camera
               index, whether optional CV deps are installed) — never
               claims "live" unless a live detector genuinely started.
"""

from datetime import datetime, timezone

import time
from fastapi import APIRouter, Depends, Request
from fastapi.responses import StreamingResponse
from sqlalchemy.orm import Session

from app.ai.factory import ai_status, get_detector, get_driver_status, get_video_frame
from app.api.deps import get_db
from app.models import Driver, SafetyEvent, Vehicle
from app.services.safety_engine import process_detection
from app.services.serializers import safety_event_to_dict

router = APIRouter()

_ONLINE_STATUSES = {"active", "on-trip"}


@router.get("/status")
def monitoring_status(db: Session = Depends(get_db)):
    drivers = [d for d in db.query(Driver).all() if d.status in _ONLINE_STATUSES and d.assigned_vehicle_id]
    results = []
    for driver in drivers:
        vehicle = db.query(Vehicle).filter(Vehicle.id == driver.assigned_vehicle_id).first()
        status = get_driver_status(driver.code, vehicle.code)
        results.append(status)
    return results


@router.get("/ai-status")
def monitoring_ai_status():
    return ai_status()


@router.get("/video-feed")
def monitoring_video_feed():
    def frame_stream():
        while True:
            frame_bytes = get_video_frame()
            if frame_bytes:
                yield (
                    b"--frame\r\n"
                    b"Content-Type: image/jpeg\r\n\r\n" + frame_bytes + b"\r\n"
                )
            time.sleep(0.033)

    return StreamingResponse(
        frame_stream(),
        media_type="multipart/x-mixed-replace; boundary=frame"
    )


@router.post("/camera-frame")
async def push_camera_frame(request: Request):
    """Receives a JPEG camera frame uploaded directly from browser / USB bridge."""
    detector = get_detector()
    if detector is None or not hasattr(detector, "camera"):
        return {"ok": False, "error": "Live camera detector is not active"}

    body = await request.body()
    if not body:
        return {"ok": False, "error": "Empty body"}

    try:
        import cv2
        import numpy as np

        nparr = np.frombuffer(body, np.uint8)
        frame = cv2.imdecode(nparr, cv2.IMREAD_COLOR)
        if frame is None:
            return {"ok": False, "error": "Failed to decode frame"}

        detector.camera.inject_frame(frame, source_name="browser_usb")
        return {"ok": True, "source": "browser_usb"}
    except Exception as exc:
        return {"ok": False, "error": str(exc)}


@router.get("/events")
def monitoring_events(db: Session = Depends(get_db), limit: int = 25):
    from app.ai.factory import active_source

    detector = get_detector()
    if active_source() == "live":
        drivers = [d for d in db.query(Driver).all() if d.code == "DRV-001" and d.status in _ONLINE_STATUSES and d.assigned_vehicle_id]
    else:
        drivers = [d for d in db.query(Driver).all() if d.status in _ONLINE_STATUSES and d.assigned_vehicle_id][:3]

    for driver in drivers:
        recent = (
            db.query(SafetyEvent)
            .filter(SafetyEvent.driver_id == driver.id)
            .order_by(SafetyEvent.timestamp.desc())
            .first()
        )
        if recent:
            recent_ts = recent.timestamp if recent.timestamp.tzinfo else recent.timestamp.replace(tzinfo=timezone.utc)
            if (datetime.now(timezone.utc) - recent_ts).total_seconds() < 15:
                continue

        vehicle = db.query(Vehicle).filter(Vehicle.id == driver.assigned_vehicle_id).first()
        if not vehicle:
            continue

        try:
            detections = detector.analyze_frame(driver.code)
        except Exception:
            # Live camera unavailable etc. — skip silently rather than
            # fabricate a result. This is the honest failure path.
            continue

        for detection in detections:
            process_detection(db, driver, vehicle, detection)

    driver_map = {d.id: d.code for d in db.query(Driver).all()}
    vehicle_map = {v.id: v.code for v in db.query(Vehicle).all()}
    events = db.query(SafetyEvent).order_by(SafetyEvent.timestamp.desc()).limit(limit).all()
    return [
        safety_event_to_dict(e, driver_map.get(e.driver_id, e.driver_id), vehicle_map.get(e.vehicle_id, e.vehicle_id))
        for e in events
    ]
